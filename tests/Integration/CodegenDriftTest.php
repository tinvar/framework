<?php

declare(strict_types=1);

/**
 * "Codegen drift. Fails if generated TypeScript is out of date with the PHP
 * signatures." The shop's committed types are what its Data classes,
 * queries, pages and actions generate now -- and `codegen --check` says
 * which file is not, when one is.
 */

namespace Tinvar\Tests\Integration\CodegenDrift;

use Tinvar\Support\PrivateDirectory;

/** @return array{int, string} the exit status and everything printed */
function codegen(string ...$arguments): array
{
    $root = \dirname(__DIR__, 4);
    $command = array_merge([PHP_BINARY, "{$root}/bin/tinvar", 'codegen'], $arguments);
    $process = proc_open($command, [1 => ['pipe', 'w'], 2 => ['pipe', 'w']], $pipes, $root);
    \assert(\is_resource($process));
    $output = stream_get_contents($pipes[1]) . stream_get_contents($pipes[2]);
    fclose($pipes[1]);
    fclose($pipes[2]);

    return [proc_close($process), (string) $output];
}

it('finds the shop\'s generated TypeScript up to date with its PHP', function () {
    [$status, $output] = codegen('--check');

    expect($status)->toBe(0, $output);
});

it('names the file that drifted, the one missing and the one left behind, and writes nothing', function () {
    $types = \dirname(__DIR__, 4) . '/examples/shop/resources/types';
    $copy = PrivateDirectory::create('tinvar-codegen');
    mkdir("{$copy}/actions");
    foreach (['generated.ts', 'modules.d.ts'] as $file) {
        copy("{$types}/{$file}", "{$copy}/{$file}");
    }
    $actions = glob("{$types}/actions/*.ts") ?: [];
    file_put_contents("{$copy}/generated.ts", "\n// edited by hand\n", FILE_APPEND);
    file_put_contents("{$copy}/actions/Removed.ts", 'export {};');
    // A mock whose query module has gone goes with it.
    mkdir("{$copy}/testing/queries", 0o700, true);
    file_put_contents("{$copy}/testing/queries/gone.ts", "// Generated by tinvar codegen. Do not edit.\nexport {};\n");
    // And one written by hand is not codegen's: not drift.
    file_put_contents("{$copy}/testing/queries/helper.ts", 'export {};');

    try {
        [$status, $output] = codegen("--out={$copy}", '--check');
        $untouched = file_get_contents("{$copy}/generated.ts");
    } finally {
        foreach ([...glob("{$copy}/actions/*") ?: [], ...glob("{$copy}/testing/queries/*") ?: []] as $file) {
            unlink($file);
        }
        rmdir("{$copy}/actions");
        rmdir("{$copy}/testing/queries");
        rmdir("{$copy}/testing");
        PrivateDirectory::remove($copy);
    }

    expect($status)->toBe(1)
        ->and($output)->toContain('generated.ts is out of date')
        ->and($output)->toContain('actions/Removed.ts is generated from nothing now')
        ->and($output)->toContain('testing/queries/gone.ts is generated from nothing now')
        ->and($output)->not->toContain('helper.ts is generated from nothing now')
        ->and($output)->toContain('testing/queries/helper.ts: tinvar codegen did not write it')
        ->and($output)->toContain('testing/fakes.ts is missing')
        ->and($output)->toContain('actions/' . basename($actions[0]) . ' is missing')
        ->and($untouched)->toEndWith("// edited by hand\n");
});

// ADR 0061: testing/ holds codegen's mocks, and a developer's helpers may sit
// beside them. Only a file that begins with codegen's header is removed.
it('removes a mock codegen wrote whose module has gone, and leaves a file written by hand', function () {
    $copy = PrivateDirectory::create('tinvar-codegen');
    mkdir("{$copy}/testing/queries", 0o700, true);
    file_put_contents("{$copy}/testing/queries/gone.ts", "// Generated by tinvar codegen. Do not edit.\nexport {};\n");
    file_put_contents("{$copy}/testing/helpers.ts", "export const seeded = 1;\n");
    file_put_contents("{$copy}/testing/queries/forged.ts", "// a copy of codegen's header, below the first two lines\n\n// Generated by tinvar codegen. Do not edit.\n");
    symlink("{$copy}/testing/helpers.ts", "{$copy}/testing/linked.ts");

    try {
        [$status, $output] = codegen("--out={$copy}");
        $gone = file_exists("{$copy}/testing/queries/gone.ts");
        $helpers = file_get_contents("{$copy}/testing/helpers.ts");
        $forged = file_exists("{$copy}/testing/queries/forged.ts");
        $linked = is_link("{$copy}/testing/linked.ts");
    } finally {
        $files = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($copy, \FilesystemIterator::SKIP_DOTS), \RecursiveIteratorIterator::CHILD_FIRST);
        foreach ($files as $file) {
            \assert($file instanceof \SplFileInfo);
            $file->isDir() && !$file->isLink() ? rmdir($file->getPathname()) : unlink($file->getPathname());
        }
        PrivateDirectory::remove($copy);
    }

    expect($status)->toBe(0, $output)
        ->and($gone)->toBeFalse()
        ->and($output)->toContain("removed {$copy}/testing/queries/gone.ts")
        ->and($helpers)->toBe("export const seeded = 1;\n")
        ->and($forged)->toBeTrue()
        ->and($linked)->toBeTrue()
        ->and($output)->toContain("left {$copy}/testing/helpers.ts: tinvar codegen did not write it")
        ->and($output)->toContain("left {$copy}/testing/queries/forged.ts: tinvar codegen did not write it")
        ->and($output)->toContain("left {$copy}/testing/linked.ts: tinvar codegen did not write it");
});
